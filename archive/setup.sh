#!/usr/bin/env bash
# WeirDing setup script — idempotent, safe to re-run.
# Installs Redis, Nginx, creates working dirs, systemd services.
set -euo pipefail

# ---------------------------------------------------------------------------
# Configurable variables (override via environment)
# ---------------------------------------------------------------------------
DATA_DIR="${WEIRDING_DATA_DIR:-/8TB/bin/weirding}"
WORK_DIR="${WEIRDING_WORK_DIR:-${DATA_DIR}}"
PORT="${WEIRDING_PORT:-8400}"
SERVER_NAME="${WEIRDING_SERVER_NAME:-localhost}"
REPO_DIR="$(cd "$(dirname "$0")" && pwd)"
WEIRDING_DIR="${REPO_DIR}"
# Determine the actual user (SUDO_USER is set when running via sudo)
if [ -n "${SUDO_USER:-}" ]; then
    RUN_USER="${SUDO_USER}"
elif [ -n "${WEIRDING_USER:-}" ]; then
    RUN_USER="${WEIRDING_USER}"
else
    RUN_USER="$(whoami)"
fi

# ---------------------------------------------------------------------------
# Colors
# ---------------------------------------------------------------------------
CYAN='\033[0;36m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
BOLD='\033[1m'
NC='\033[0m' # No Color

info()  { echo -e "${CYAN}[INFO]${NC}  $*"; }
ok()    { echo -e "${GREEN}[ OK ]${NC}  $*"; }
warn()  { echo -e "${YELLOW}[WARN]${NC}  $*"; }
fail()  { echo -e "${RED}[FAIL]${NC}  $*"; }
fatal() { fail "$@"; exit 1; }

# ---------------------------------------------------------------------------
# Banner
# ---------------------------------------------------------------------------
echo -e "${BOLD}${CYAN}"
cat << 'BANNER'
BANNER
echo -e "${NC}"
info "WeirDing setup — $(date)"
info "Repo:       ${REPO_DIR}"
info "Work dir:   ${WORK_DIR}"
info "Port:       ${PORT}"
info "Server:     ${SERVER_NAME}"
info "User:       ${RUN_USER}"
echo ""

# ---------------------------------------------------------------------------
# 1. Pre-flight checks
# ---------------------------------------------------------------------------
info "Running pre-flight checks..."

# Python 3
if command -v python3 &>/dev/null; then
    PY_VER="$(python3 --version 2>&1)"
    ok "Python 3 found: ${PY_VER}"
else
    fatal "Python 3 not found. Install python3 first."
fi

# uv
if [ -n "${SUDO_USER:-}" ]; then
    # Running with sudo — check as the actual user with login shell
    UV_PATH="$(sudo -i -u "${RUN_USER}" bash -c 'command -v uv' 2>/dev/null || echo '')"
else
    UV_PATH="$(command -v uv 2>/dev/null || echo '')"
fi

if [ -n "${UV_PATH}" ]; then
    UV_VER="$(sudo -u "${RUN_USER}" "${UV_PATH}" --version 2>&1)"
    ok "uv found: ${UV_VER} (${UV_PATH})"
else
    fatal "uv not found for user ${RUN_USER}. Install with: curl -LsSf https://astral.sh/uv/install.sh | sh"
fi

# ffmpeg
if command -v ffmpeg &>/dev/null; then
    ok "ffmpeg found"
else
    fatal "ffmpeg not found. Install with: sudo apt install ffmpeg"
fi

# CUDA
if command -v nvidia-smi &>/dev/null; then
    GPU_NAME="$(nvidia-smi --query-gpu=name --format=csv,noheader 2>/dev/null | head -1)"
    ok "CUDA available: ${GPU_NAME}"
else
    warn "nvidia-smi not found — CUDA may not be available. TTS requires a GPU."
fi

echo ""

# ---------------------------------------------------------------------------
# 2. Redis
# ---------------------------------------------------------------------------
info "Checking Redis..."

if command -v redis-server &>/dev/null; then
    ok "Redis already installed"
else
    info "Installing Redis via apt..."
    sudo apt-get update -qq
    sudo apt-get install -y -qq redis-server
    ok "Redis installed"
fi

# Ensure Redis is running
if systemctl is-active --quiet redis-server 2>/dev/null; then
    ok "Redis is running"
else
    info "Starting Redis..."
    sudo systemctl enable --now redis-server
    ok "Redis started and enabled"
fi

# Quick connectivity check on DB 1
if command -v redis-cli &>/dev/null; then
    if redis-cli -n 1 PING 2>/dev/null | grep -q PONG; then
        ok "Redis DB 1 responding"
    else
        warn "Redis DB 1 did not respond to PING — check redis-server status"
    fi
fi

echo ""

# ---------------------------------------------------------------------------
# 3. Nginx
# ---------------------------------------------------------------------------
info "Checking Nginx..."

if command -v nginx &>/dev/null; then
    ok "Nginx already installed"
else
    info "Installing Nginx via apt..."
    sudo apt-get update -qq
    sudo apt-get install -y -qq nginx
    ok "Nginx installed"
fi

NGINX_CONF="/etc/nginx/sites-available/weirding"
NGINX_LINK="/etc/nginx/sites-enabled/weirding"

if [ -f "${NGINX_CONF}" ]; then
    warn "Nginx config already exists at ${NGINX_CONF} — skipping (will not overwrite)"
else
    info "Creating Nginx site config..."
    sudo tee "${NGINX_CONF}" > /dev/null << NGINX_EOF
# WeirDing — generated by setup.sh on $(date -Iseconds)
server {
    listen 80;
    server_name ${SERVER_NAME};

    client_max_body_size 500M;

    # Serve static files directly
    location /static/ {
        alias ${WORK_DIR}/static/;
        expires 7d;
        add_header Cache-Control "public, immutable";
    }

    # Proxy to WeirDing app
    location / {
        proxy_pass http://127.0.0.1:${PORT};
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;

        # SSE support — disable buffering
        proxy_buffering off;
        proxy_cache off;
        proxy_set_header Connection '';
        proxy_http_version 1.1;
        chunked_transfer_encoding off;

        proxy_read_timeout 300s;
        proxy_send_timeout 300s;
    }
}
NGINX_EOF
    ok "Nginx config written to ${NGINX_CONF}"

    if [ ! -L "${NGINX_LINK}" ]; then
        sudo ln -s "${NGINX_CONF}" "${NGINX_LINK}"
        ok "Nginx site enabled"
    fi

    # Test config before reload
    if sudo nginx -t 2>/dev/null; then
        sudo systemctl reload nginx
        ok "Nginx config tested and reloaded"
    else
        warn "Nginx config test failed — run 'sudo nginx -t' to debug"
    fi
fi

echo ""

# ---------------------------------------------------------------------------
# 4. Working directory structure
# ---------------------------------------------------------------------------
info "Creating working directory structure at ${WORK_DIR}..."

sudo mkdir -p "${WORK_DIR}/data/uploads" \
              "${WORK_DIR}/data/chunks" \
              "${WORK_DIR}/data/output" \
              "${WORK_DIR}/data/voices" \
              "${WORK_DIR}/static"

sudo chown -R "${RUN_USER}:" "${WORK_DIR}"
ok "Directory structure created"

# Symlink static files from repo into WORK_DIR
if [ -d "${WEIRDING_DIR}/static" ]; then
    # Symlink each file individually so WORK_DIR/static/ can also hold generated assets
    for src_file in "${WEIRDING_DIR}/static/"*; do
        [ -e "${src_file}" ] || continue
        base="$(basename "${src_file}")"
        target="${WORK_DIR}/static/${base}"
        if [ -L "${target}" ]; then
            # Re-create if pointing elsewhere
            current="$(readlink -f "${target}")"
            if [ "${current}" != "$(readlink -f "${src_file}")" ]; then
                ln -sf "${src_file}" "${target}"
                info "Updated symlink: ${target}"
            fi
        elif [ ! -e "${target}" ]; then
            ln -s "${src_file}" "${target}"
        else
            warn "Static file ${target} exists and is not a symlink — skipping"
        fi
    done
    ok "Static files symlinked"
else
    warn "No static directory found at ${WEIRDING_DIR}/static"
fi

echo ""

# ---------------------------------------------------------------------------
# 5. Port conflict check
# ---------------------------------------------------------------------------
info "Checking port ${PORT}..."

if ss -tlnp 2>/dev/null | grep -q ":${PORT} "; then
    PROC="$(ss -tlnp 2>/dev/null | grep ":${PORT} " | head -1)"
    warn "Port ${PORT} is already in use:"
    warn "  ${PROC}"
    warn "If this is a previous WeirDing instance, stop it before starting a new one."
else
    ok "Port ${PORT} is available"
fi

echo ""

# ---------------------------------------------------------------------------
# 6. Systemd service files
# ---------------------------------------------------------------------------
info "Creating systemd service files..."

WEB_SERVICE="/etc/systemd/system/weirding-web.service"
WORKER_SERVICE="/etc/systemd/system/weirding-worker.service"

sudo tee "${WEB_SERVICE}" > /dev/null << SERVICE_EOF
[Unit]
Description=WeirDing Web (FastAPI)
After=network.target redis-server.service
Requires=redis-server.service

[Service]
Type=simple
User=${RUN_USER}
WorkingDirectory=${REPO_DIR}
Environment=WEIRDING_WORK_DIR=${WORK_DIR}
ExecStart=${UV_PATH} run app.py
Restart=on-failure
RestartSec=5

[Install]
WantedBy=multi-user.target
SERVICE_EOF
ok "Created ${WEB_SERVICE}"

sudo tee "${WORKER_SERVICE}" > /dev/null << SERVICE_EOF
[Unit]
Description=WeirDing Worker (Celery)
After=network.target redis-server.service
Requires=redis-server.service

[Service]
Type=simple
User=${RUN_USER}
WorkingDirectory=${REPO_DIR}
Environment=WEIRDING_WORK_DIR=${WORK_DIR}
ExecStart=${UV_PATH} run worker.py
Restart=on-failure
RestartSec=5

[Install]
WantedBy=multi-user.target
SERVICE_EOF
ok "Created ${WORKER_SERVICE}"

sudo systemctl daemon-reload
ok "Systemd daemon reloaded"

echo ""

# ---------------------------------------------------------------------------
# Done
# ---------------------------------------------------------------------------
echo -e "${GREEN}${BOLD}Setup complete!${NC}"
echo ""
echo -e "${CYAN}To start WeirDing:${NC}"
echo "  sudo systemctl start weirding-web weirding-worker"
echo ""
echo -e "${CYAN}To enable on boot:${NC}"
echo "  sudo systemctl enable weirding-web weirding-worker"
echo ""
echo -e "${CYAN}To check status:${NC}"
echo "  systemctl status weirding-web weirding-worker"
echo ""
echo -e "${CYAN}To view logs:${NC}"
echo "  journalctl -u weirding-web -f"
echo "  journalctl -u weirding-worker -f"
echo ""
echo -e "${CYAN}Web UI:${NC}  http://${SERVER_NAME} (via Nginx)"
echo -e "${CYAN}Direct:${NC}  http://localhost:${PORT}"
echo ""
